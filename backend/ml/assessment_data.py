def get_trade_assessment_questions(skill_name: str, language: str = "en"):
    """
    Returns AT LEAST 10 scenario-based practical questions for any of the 10 trades.
    Full support for English and Tamil.
    """
    bank = ASSESSMENT_QUESTION_BANKS.get(skill_name)
    if not bank:
        # Fallback to Electrician or Plumber
        bank = ASSESSMENT_QUESTION_BANKS.get("Electrician", [])

    formatted = []
    for q in bank[:10]:
        is_tamil = (language == "ta")
        formatted.append({
            "id": q["id"],
            "q_no": q["q_no"],
            "question": q["question_ta"] if is_tamil else q["question_en"],
            "options": q["options_ta"] if is_tamil else q["options_en"],
            "correct_index": q["correct_index"],
            "explanation": q["explanation_ta"] if is_tamil else q["explanation_en"],
            "voice_prompt": q["voice_prompt_ta"] if is_tamil else q["voice_prompt_en"],
            "key_concepts": q["key_concepts_ta"] if is_tamil else q["key_concepts_en"]
        })
    return formatted


def evaluate_worker_voice_answer(
    question_id: str,
    skill_name: str,
    spoken_text: str,
    selected_option_idx: int = None,
    language: str = "en"
):
    """
    Evaluates worker voice/text answer semantically based on:
    - Practical knowledge
    - Safety awareness
    - Correct procedure
    - Tool knowledge
    - Problem-solving ability
    Returns score out of 10, matched concepts, and natural feedback in chosen language.
    """
    bank = ASSESSMENT_QUESTION_BANKS.get(skill_name, [])
    question_data = next((q for q in bank if q["id"] == question_id), None)
    
    is_tamil = (language == "ta")

    if not question_data:
        return {
            "score": 7.0,
            "feedback": "பதில் பதிவு செய்யப்பட்டது." if is_tamil else "Answer recorded.",
            "concepts_recognized": []
        }

    correct_idx = question_data["correct_index"]
    key_concepts = question_data["key_concepts_ta"] if is_tamil else question_data["key_concepts_en"]

    score = 0.0
    matched_concepts = []

    # 1. Option match if provided (e.g. spoken number or matched button)
    option_correct = (selected_option_idx == correct_idx)
    if option_correct:
        score += 6.0

    # 2. Semantic voice text analysis: Check for presence of domain-correct concepts
    text_lower = (spoken_text or "").lower()
    for concept in key_concepts:
        if concept.lower() in text_lower:
            matched_concepts.append(concept)
            score += 1.5

    # If worker answered well in spoken words even without clicking MCQ
    if len(matched_concepts) >= 2 and not option_correct:
        score = max(score, 7.5)

    # Score bounded between 0 and 10
    final_score = min(10.0, max(1.0 if spoken_text else 0.0, score))
    final_score = round(final_score, 1)

    # Generate natural conversational feedback
    if is_tamil:
        if final_score >= 8.0:
            feedback = "சிறந்த விளக்கம்! உங்கள் செய்முறை அறிவும் பாதுகாப்பு விழிப்புணர்வும் மிகச் சரியாக உள்ளது."
        elif final_score >= 6.0:
            feedback = "சரியான பதில். பணி முறையை தெளிவாக புரிந்து வைத்துள்ளீர்கள்."
        elif final_score >= 4.0:
            feedback = "ஓரளவு சரியான பதில். பாதுகாப்பு நடைமுறைகளில் கூடுதல் கவனம் தேவை."
        else:
            feedback = "பதில் துல்லியமாக இல்லை. சரியான முறை: " + question_data["explanation_ta"]
    else:
        if final_score >= 8.0:
            feedback = "Excellent! Your practical reasoning and safety awareness are spot on."
        elif final_score >= 6.0:
            feedback = "Good answer. You demonstrated sound working knowledge of the procedure."
        elif final_score >= 4.0:
            feedback = "Partially correct. Further attention to safety and tool procedure is recommended."
        else:
            feedback = "Incorrect procedure. Recommended practice: " + question_data["explanation_en"]

    return {
        "score": final_score,
        "max_score": 10.0,
        "feedback": feedback,
        "matched_concepts": matched_concepts,
        "explanation": question_data["explanation_ta"] if is_tamil else question_data["explanation_en"]
    }
